"""Generate Rust scheduling constants from the same manifest the browser loads."""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
m=json.loads((root/'shaders/compute/manifest.json').read_text())
s='// Generated by tools/generate_passes.py. Do not edit.\n'
for key,name in [('beforePressure','BEFORE'),('pressure','PRESSURE'),('afterPressure','AFTER'),('detail','DETAIL')]:
 s+=f'pub const {name}: &[(&str,&str)] = &[\n'
 for entry,kind in m[key]:s+=f'    ("{entry}","{kind}"),\n'
 s+='];\n'
p=root/'crates/vapor-backend/src/passes.rs'
if '--check' in sys.argv:
 if not p.exists() or p.read_text()!=s:raise SystemExit('FAIL GPU scheduling constants are stale')
 print('PASS shared GPU schedule')
else:p.write_text(s)
